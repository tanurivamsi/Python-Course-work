#Numerical DataTypes

#int DataType
a = 10
print("Type of a is : ",type(a))
#Float DataType
b=2.1
print("Type of b is : ",type(b))
#complex DataType
c = 122.22j
print("Type of c is : ",type(c))
#string DataType(seqeuncial)
d = "Vamsi"
print("Type of d is : ",type(d))
#list DataType
e = ['tanuri','vamsi']
print("Type of e is : ",type(e))
#tuple DataType
f = ('1','Vamsi')
print("Type of f is : ",type(f))
#set DataType(Mapping)
g = {1212,"Vamsi","212.3212"}
print("Type of g is : ",type(g))
#Dictionary DataType
h = {1:"vamsi",2:"Rishi"}
print("Type of h is : ",type(h))
#Boolean DataType
i = True
j = False
print("Type of i and j is : ",type(i))
#None DataType
k = None
print("Type of k is : ",type(k))


